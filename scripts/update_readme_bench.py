"""Run the benchmarks and write the results to docs/BENCHMARKS.md and the README."""

from __future__ import annotations

import argparse
import sys
from pathlib import Path

START = "<!-- BENCH:START -->"
END = "<!-- BENCH:END -->"


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description="Update benchmark results in the docs")
    parser.add_argument("--quick", action="store_true", help="small sizes, one repeat")
    args = parser.parse_args(argv)

    root = Path(__file__).resolve().parent.parent
    sys.path.insert(0, str(root / "benchmarks"))
    from bench_solver import QUICK, build_report

    readme = root / "README.md"
    text = readme.read_text(encoding="utf-8")
    start = text.find(START)
    end = text.find(END)
    if start == -1 or end == -1 or end < start:
        print(f"error: README.md must contain {START} and {END}", file=sys.stderr)
        return 1

    report = build_report(**QUICK) if args.quick else build_report()

    docs = root / "docs"
    docs.mkdir(exist_ok=True)
    header = (
        "# Benchmarks\n\n"
        "Generated by `python scripts/update_readme_bench.py`. Do not edit by hand.\n\n"
    )
    (docs / "BENCHMARKS.md").write_text(header + report + "\n", encoding="utf-8", newline="\n")
    updated = text[: start + len(START)] + "\n" + report + "\n" + text[end:]
    readme.write_text(updated, encoding="utf-8", newline="\n")
    print("Updated docs/BENCHMARKS.md and README.md")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
